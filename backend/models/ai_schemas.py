class QuizGenerationRequest(BaseModel):
    topic_id: Optional[str] = Field(None, description="The ID of the BookTopic to generate the quiz from.")
    book_id: Optional[str] = Field(None, description="The ID of the Book - will use random topic if topic_id not provided.")
    num_questions: int = Field(10, ge=1, le=20, description="Number of questions to generate. Defaults to 10 as per plan.")
# --- End of modification ---

class QuizQuestion(BaseModel):
    question_text: str = Field(..., description="The question generated by the AI.")
    correct_answer: str = Field(..., description="The precise, short AI-generated correct answer.")
    answer_variants: List[str] = Field(..., description="A list of acceptable, alternative answers.") # <-- ADD THIS
    explanation: str = Field(..., description="A brief explanation for the correct answer.")

class GeneratedQuiz(BaseModel):
    quiz_id: str = Field(..., description="A temporary ID for tracking the quiz session (e.g., a hash or UUID).")
    book_id: str = Field(..., description="The ID of the book this quiz belongs to.")
    topic_name: str = Field(..., description="The name/subject of the quiz topic.")
    questions: List[QuizQuestion] = Field(..., description="The list of questions and their correct answers.")

class UserAnswer(BaseModel):
    question_text: str = Field(..., description="The original question text (for verification).")
    user_answer: str = Field(..., description="The user's short answer attempt.")

class QuizEvaluationRequest(BaseModel):
    quiz_id: str = Field(..., description="The temporary ID of the quiz being evaluated.")
    attempted_answers: List[UserAnswer]
    book_id: str = Field(..., description="The ID of the book this quiz belongs to.")
    topic_name: str = Field(..., description="The name or identifier of the topic the quiz was for.")

class EvaluatedQuestionResult(BaseModel):
    question_text: str
    user_answer: str
    correct_answer: str
    correct_explanation: str 
    similarity_score: float = Field(..., ge=0.0, le=1.0, description="Cosine similarity between user answer and correct answer.")

class QuizEvaluationResponse(BaseModel):
    quiz_id: str
    total_score: float = Field(..., ge=0.0, le=1.0, description="The average similarity score across all questions (0.0 to 1.0).")
    total_grade: str = Field(..., description="A letter grade or qualitative description based on total_score.")
    results: List[EvaluatedQuestionResult]
    book_id: str | None = Field(None, description="The ID of the book this quiz belongs to, for progress tracking.")
    
    # AI Mentor Recommendations
    study_recommendations: Optional[str] = Field(None, description="Personalized study plan from AI mentor.")
    weak_topics: Optional[List[str]] = Field(None, description="Topics the student struggled with.")
    strong_topics: Optional[List[str]] = Field(None, description="Topics the student knows well.")
    next_steps: Optional[List[str]] = Field(None, description="Actionable next steps for improvement.")

