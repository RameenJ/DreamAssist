class AIMentorMessageInDB(BaseModel):
    """Schema for storing AI Mentor chat messages in MongoDB."""
    id: PyObjectId = Field(default_factory=PyObjectId, alias="_id")
    conversation_id: PyObjectId = Field(..., description="The conversation this message belongs to")
    user_id: PyObjectId = Field(..., description="The user who is chatting with the AI")
    book_id: PyObjectId = Field(..., description="The book being discussed")
    sender_type: Literal["user", "ai"] = Field(..., description="Whether this message is from user or AI")
    content: str = Field(..., description="The message content")
    sources: Optional[List[str]] = Field(None, description="Source chunks used by AI (only for AI messages)")
    created_at: datetime = Field(default_factory=datetime.utcnow)
    
    # Placeholder fields for future sentiment analysis
    user_emotion: Optional[str] = Field(None, description="Detected emotion (will be populated by DistilBERT model)")
    sentiment_score: Optional[float] = Field(None, description="Sentiment score from DistilBERT model")
    
    class Config:
        populate_by_name = True
        arbitrary_types_allowed = True
        json_encoders = {ObjectId: str, PyObjectId: str, datetime: lambda dt: dt.isoformat()}

